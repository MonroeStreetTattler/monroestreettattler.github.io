"""Prebuild the coverage area for the Worker from ../boundary.json, using the Python
reference geometry, so the Worker never traces the outline at request time.

  python3 scripts/build_area.py           write src/area-data.js and test/area-points.json
  python3 scripts/build_area.py --check   fail if either file is out of date

The test points let the Worker's in-area check be compared with the Python one.
"""

import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)                    # cloudflare/
SERVICE = os.path.dirname(ROOT)                 # santa-map/
sys.path.insert(0, SERVICE)

from santa_map.geo import load_boundary  # noqa: E402

AREA_JS = os.path.join(ROOT, 'src', 'area-data.js')
POINTS_JSON = os.path.join(ROOT, 'test', 'area-points.json')


def build():
    with open(os.path.join(SERVICE, 'boundary.json'), encoding='utf-8') as f:
        raw = json.load(f)
    b = load_boundary(os.path.join(SERVICE, 'boundary.json'))
    area = {'name': b.name, 'radius_m': b.radius_m, 'bounds': b.bounds(), 'rings': b.outline_rings()}
    data = {'name': b.name, 'radius_m': b.radius_m,
            'lines': [[[p['lat'], p['lon']] for p in line['points']] for line in raw['lines']],
            'lat0': b.lat0, 'area': area}
    js = ('// Generated by scripts/build_area.py from ../boundary.json. Do not edit.\n'
          'export default ' + json.dumps(data, separators=(',', ':')) + ';\n')

    # A grid across the area plus points just inside and outside the edge.
    (s, w), (n, e) = area['bounds']
    points = []
    for i in range(25):
        for j in range(25):
            lat, lon = s + (n - s) * i / 24, w + (e - w) * j / 24
            points.append([round(lat, 6), round(lon, 6)])
    for ring in area['rings']:
        for lat, lon in ring[::20]:
            points.append([lat, lon])
    expected = [[lat, lon, b.contains(lat, lon), round(b.distance_m(lat, lon), 3)] for lat, lon in points]
    # Points within 1 m of the edge are left out: they are rounding, not policy.
    expected = [p for p in expected if abs(p[3] - b.radius_m) > 1]
    points_text = json.dumps(expected, separators=(',', ':')) + '\n'
    return js, points_text


def main():
    js, points = build()
    if '--check' in sys.argv:
        stale = [p for p, want in ((AREA_JS, js), (POINTS_JSON, points))
                 if not os.path.exists(p) or open(p, encoding='utf-8').read() != want]
        if stale:
            sys.exit('out of date: ' + ', '.join(os.path.relpath(p, ROOT) for p in stale))
        print('area data up to date')
        return
    for path, text in ((AREA_JS, js), (POINTS_JSON, points)):
        with open(path, 'w', encoding='utf-8') as f:
            f.write(text)
    print(f'wrote {os.path.relpath(AREA_JS, ROOT)} ({len(js)} bytes) and {os.path.relpath(POINTS_JSON, ROOT)}')


if __name__ == '__main__':
    main()
